"""D6 bounded first-slice tests (docs/DECISIONS.md; interface + fake only).

Only an in-process fake provider is used here — app/github_publication.py
itself registers no concrete implementation, contacts no network, and is not
imported by any approval/API/execution code path (grep-checked below).
"""

from __future__ import annotations

import ast
from pathlib import Path

import pytest

from app.github_publication import (
    DraftPullRequestRequest,
    DraftPullRequestResult,
    GitHubPublicationProvider,
)


class FakeGitHubPublicationProvider(GitHubPublicationProvider):
    """In-process test double. Never touches a network or a real credential."""

    def __init__(self, *, next_pull_request_number: int = 1):
        self._next_pull_request_number = next_pull_request_number
        self.received_requests: list[DraftPullRequestRequest] = []

    @property
    def provider_id(self) -> str:
        return "fake-github-v1"

    def create_draft_pull_request(
        self, request: DraftPullRequestRequest
    ) -> DraftPullRequestResult:
        self.received_requests.append(request)
        number = self._next_pull_request_number
        self._next_pull_request_number += 1
        return DraftPullRequestResult(
            provider_id=self.provider_id,
            repository=request.repository,
            pull_request_number=number,
            pull_request_url=(
                f"https://example.invalid/{request.repository}/pull/{number}"
            ),
            head_branch=request.head_branch,
            is_draft=True,
        )


def _request(**overrides) -> DraftPullRequestRequest:
    values = dict(
        repository="octo/example",
        base_branch="main",
        head_branch="engineering-task/123",
        title="Automated change",
        body="Generated by an Engineering Task run.",
        bundle_ref="sha256:" + "a" * 64,
    )
    values.update(overrides)
    return DraftPullRequestRequest(**values)


