def test_fake_provider_creates_a_draft_pull_request():
    provider = FakeGitHubPublicationProvider(next_pull_request_number=42)
    request = _request()

    result = provider.create_draft_pull_request(request)

    assert result.is_draft is True
    assert result.provider_id == "fake-github-v1"
    assert result.repository == "octo/example"
    assert result.pull_request_number == 42
    assert result.head_branch == "engineering-task/123"
    assert provider.received_requests == [request]


def test_fake_provider_never_merges_or_reuses_pull_request_numbers():
    provider = FakeGitHubPublicationProvider()
    first = provider.create_draft_pull_request(_request())
    second = provider.create_draft_pull_request(_request(head_branch="other-branch"))

    assert first.pull_request_number != second.pull_request_number
    assert {first.is_draft, second.is_draft} == {True}
